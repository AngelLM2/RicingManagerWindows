<#
.SYNOPSIS
    The settings window's translations (docs/04 M7): every @tr("...") of apps\settings\ui, each
    language's apps\settings\lang\<lang>.tsv (English<TAB>translation, one per line) turned into the
    gettext .po Slint builds in (lang\<lang>\LC_MESSAGES\rmw-settings.po).
.DESCRIPTION
    Fails when a text has no translation, or a translation has no text any more, so a new string
    never ships in English by accident.
.EXAMPLE
    .\scripts\translations.ps1          # check and write the .po files
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$ui = Join-Path $root 'apps\settings\ui'
$lang = Join-Path $root 'apps\settings\lang'
$utf8 = New-Object Text.UTF8Encoding $false

$ids = New-Object System.Collections.Generic.List[string]
foreach ($file in Get-ChildItem $ui -Recurse -Filter *.slint) {
    $text = [IO.File]::ReadAllText($file.FullName)
    foreach ($match in [regex]::Matches($text, '@tr\("((?:[^"\\]|\\.)*)"')) {
        $id = $match.Groups[1].Value -replace '\\"', '"' -replace '\\\\', '\'
        if (-not $ids.Contains($id)) { $ids.Add($id) }
    }
}

function Quote([string] $Text) {
    '"' + ($Text -replace '\\', '\\' -replace '"', '\"') + '"'
}

$failed = $false
foreach ($tsv in Get-ChildItem $lang -Filter *.tsv) {
    $language = $tsv.BaseName
    # Case matters ("Left" and "left" are two texts); .Keys would read an entry called "Keys".
    $pairs = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::Ordinal)
    foreach ($line in [IO.File]::ReadAllLines($tsv.FullName, $utf8)) {
        if ($line.Trim() -eq '') { continue }
        $parts = $line.Split("`t")
        if ($parts.Count -ne 2) { Write-Warning "$($tsv.Name): not English<TAB>translation: $line"; $failed = $true; continue }
        $pairs[$parts[0]] = $parts[1]
    }
    $missing = @($ids | Where-Object { -not $pairs.ContainsKey($_) })
    $stale = @($pairs.get_Keys() | Where-Object { -not $ids.Contains($_) })
    foreach ($id in $missing) { Write-Warning "${language}: no translation for: $id"; $failed = $true }
    foreach ($id in $stale) { Write-Warning "${language}: translated but no longer used: $id"; $failed = $true }

    $po = New-Object System.Text.StringBuilder
    [void]$po.AppendLine('# Generated by scripts\translations.ps1 from ' + $tsv.Name + ': edit that file.')
    [void]$po.AppendLine('msgid ""')
    [void]$po.AppendLine('msgstr ""')
    [void]$po.AppendLine('"Content-Type: text/plain; charset=UTF-8\n"')
    [void]$po.AppendLine("`"Language: $language\n`"")
    [void]$po.AppendLine('"Plural-Forms: nplurals=2; plural=(n > 1);\n"')
    foreach ($id in $ids) {
        if (-not $pairs.ContainsKey($id)) { continue }
        [void]$po.AppendLine()
        [void]$po.AppendLine('msgid ' + (Quote $id))
        [void]$po.AppendLine('msgstr ' + (Quote $pairs[$id]))
    }
    $target = Join-Path $lang "$language\LC_MESSAGES\rmw-settings.po"
    New-Item -ItemType Directory -Force (Split-Path $target) | Out-Null
    [IO.File]::WriteAllText($target, $po.ToString().Replace("`r`n", "`n"), $utf8) # LF, like the repository
    Write-Host "${language}: $($pairs.Count) of $($ids.Count) texts -> $target"
}
if ($failed) { throw 'Translations are not complete.' }
